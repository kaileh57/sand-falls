impl Image {
    /// Draws text with its top-left corner at `(x, y)`, each font pixel `size` pixels wide,
    /// with a one-pixel dark shadow so it reads on any background.
    pub fn text(&mut self, x: i32, y: i32, size: i32, s: &str, color: [u8; 4]) {
        let size = size.max(1);
        let mut cx = x;
        for ch in s.chars() {
            let g = glyph(ch);
            for (row, bits) in g.iter().enumerate() {
                for col in 0..5 {
                    if bits & (0x10 >> col) != 0 {
                        for dy in 0..size {
                            for dx in 0..size {
                                let px = cx + col * size + dx;
                                let py = y + row as i32 * size + dy;
                                self.put(px + 1, py + 1, [0, 0, 0, 255]);
                                self.put(px, py, color);
                            }
                        }
                    }
                }
            }
            cx += 6 * size;
        }
    }

    /// Draws one line of text centered across the image on a dark panel, at
    /// double size when it fits. Used for a game's status line.
    pub fn banner(&mut self, y: i32, s: &str, color: [u8; 4]) {
        let chars = s.chars().count() as i32;
        let w = self.width as i32;
        let size = if chars * 12 + 16 <= w { 2 } else { 1 };
        let tw = chars * 6 * size;
        let x = ((w - tw) / 2).max(4);
        self.shade(x - 6, y - 4, x + tw + 6, y + 7 * size + 5, 150);
        self.text(x, y, size, s, color);
    }

    /// Darkens a rectangle, for text panels.
    pub fn shade(&mut self, x0: i32, y0: i32, x1: i32, y1: i32, alpha: u8) {
        for y in y0.max(0)..y1.min(self.height as i32) {
            for x in x0.max(0)..x1.min(self.width as i32) {
                let i = (y as usize * self.width as usize + x as usize) * 4;
                for c in 0..3 {
                    self.rgba[i + c] =
                        (u16::from(self.rgba[i + c]) * u16::from(255 - alpha) / 255) as u8;
                }
            }
        }
    }

    /// Draws a filled rectangle.
    pub fn fill(&mut self, x0: i32, y0: i32, x1: i32, y1: i32, c: [u8; 4]) {
        for y in y0..y1 {
            for x in x0..x1 {
                self.put(x, y, c);
            }
        }
    }
}
